"""Deterministic evidence-bundle builder (oept-bundle/0.1).

A bundle is a deterministic ZIP with a canonical-JSON manifest. The manifest
lists and hashes every member except itself. Determinism inputs: sorted
member paths, fixed ZIP timestamps, fixed permission bits, DEFLATE
compression, canonical JSON payloads.

Reproducibility boundary (stated honestly): identical logical inputs
produce identical manifest bytes on any platform. Complete-ZIP-byte
identity additionally depends on the Python/zlib ZIP implementation and
is asserted only for same-interpreter round-trips in the test suite.
"""

from __future__ import annotations

import io
import zipfile
from collections.abc import Mapping
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from .canonical import canonicalize_json
from .errors import ValidationError
from .hashing import sha256_bytes
from .models import utc_now_iso

BUNDLE_SPEC_VERSION = "oept-bundle/0.1"

#: Fixed DOS timestamp used for every ZIP member (reproducibility).
FIXED_ZIP_DATE_TIME = (2024, 1, 1, 0, 0, 0)

#: Fixed unix permission bits for ZIP members (0o644 << 16).
FIXED_EXTERNAL_ATTR = 0o644 << 16

REQUIRED_MEMBERS = ("manifest.json", "facts.json", "provenance.json")

EVIDENCE_PREFIX = "evidence/"


@dataclass
class BundleFile:
    """One logical bundle member: archive path + exact bytes."""

    path: str
    data: bytes

    @property
    def sha256(self) -> str:
        return sha256_bytes(self.data)


def _check_member_path(path: str) -> None:
    if not path or path.startswith("/") or "\\" in path or "\x00" in path:
        raise ValidationError(f"unsafe bundle member path: {path!r}")
    parts = path.split("/")
    if any(part in ("", ".", "..") for part in parts):
        raise ValidationError(f"unsafe bundle member path: {path!r}")
    if len(path) > 512:
        raise ValidationError(f"bundle member path too long: {path!r}")


@dataclass
class BundleBuilder:
    """Accumulates members, then emits manifest + deterministic ZIP."""

    bundle_id: str
    created_at: str = ""
    _files: dict[str, bytes] = field(default_factory=dict)
    key_id: str | None = None

    def __post_init__(self) -> None:
        if not self.bundle_id or not self.bundle_id.strip():
            raise ValidationError("bundle_id must be non-empty")
        if not self.created_at:
            self.created_at = utc_now_iso()

    def add_file(self, path: str, data: bytes) -> BundleBuilder:
        """Add one member. Duplicate paths are rejected (never overwritten)."""
        _check_member_path(path)
        if path in self._files:
            raise ValidationError(f"duplicate bundle member path: {path!r}")
        if path == "manifest.json":
            raise ValidationError("manifest.json is generated by the builder")
        if path == "signatures/manifest.sig":
            raise ValidationError(
                "signatures/manifest.sig is reserved for the signature; "
                "pass signature= to build_zip_bytes instead"
            )
        self._files[path] = bytes(data)
        return self

    def add_evidence(self, name: str, data: bytes) -> BundleBuilder:
        """Add raw evidence bytes under evidence/."""
        return self.add_file(f"{EVIDENCE_PREFIX}{name}", data)

    def manifest_dict(self) -> dict[str, Any]:
        """Canonical manifest object (without signature members)."""
        for required in ("facts.json", "provenance.json"):
            if required not in self._files:
                raise ValidationError(f"bundle is missing required member: {required}")
        entries = [
            {"path": path, "sha256": sha256_bytes(data), "size_bytes": len(data)}
            for path, data in sorted(self._files.items())
        ]
        manifest: dict[str, Any] = {
            "bundle_spec_version": BUNDLE_SPEC_VERSION,
            "bundle_id": self.bundle_id,
            "created_at": self.created_at,
            "files": entries,
        }
        if self.key_id:
            manifest["key_id"] = self.key_id
        return manifest

    def manifest_bytes(self) -> bytes:
        """Canonical manifest bytes (the exact bytes that get signed)."""
        return canonicalize_json(self.manifest_dict())

    def _zip_members(self, signature: bytes | None = None) -> dict[str, bytes]:
        members = dict(self._files)
        if signature is not None:
            if "signatures/manifest.sig" in members:
                raise ValidationError("signatures/manifest.sig is reserved for the signature")
            members["signatures/manifest.sig"] = signature
        members["manifest.json"] = self.manifest_bytes()
        return members

    def build_zip_bytes(self, signature: bytes | None = None) -> bytes:
        """Emit the deterministic ZIP.

        Envelope rule (see spec/bundle-spec.md): signatures/manifest.sig is
        written into the archive but is deliberately NOT listed in
        manifest.json's file table, so signature verification never needs
        the signature to check itself. signatures/key-info.json, when added
        via add_file, IS listed and therefore bound to the signed payload
        (its key_id stays identification-only; trust is caller-supplied).
        """
        members = self._zip_members(signature)
        buffer = io.BytesIO()
        with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
            for path in sorted(members):
                info = zipfile.ZipInfo(path, date_time=FIXED_ZIP_DATE_TIME)
                info.compress_type = zipfile.ZIP_DEFLATED
                info.external_attr = FIXED_EXTERNAL_ATTR
                info.create_system = 3
                archive.writestr(info, members[path])
        return buffer.getvalue()

    def write_zip(self, output: str | Path, signature: bytes | None = None) -> Path:
        """Write the deterministic ZIP to disk."""
        target = Path(output)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(self.build_zip_bytes(signature))
        return target


def build_bundle(
    files: Mapping[str, bytes],
    bundle_id: str,
    created_at: str = "",
    signature: bytes | None = None,
    key_id: str | None = None,
) -> bytes:
    """One-shot helper: members + id -> deterministic ZIP bytes."""
    builder = BundleBuilder(bundle_id=bundle_id, created_at=created_at, key_id=key_id)
    for path in sorted(files):
        builder.add_file(path, files[path])
    manifest = builder.manifest_dict()
    if signature is not None and not manifest.get("key_id") and key_id is None:
        raise ValidationError(
            "signed bundles must carry a key_id label "
            "(identification only; trust comes from caller-supplied keys)"
        )
    return builder.build_zip_bytes(signature)
